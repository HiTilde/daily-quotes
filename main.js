window.onload = function generateRandom() {
    // RI - random index
    // Create RI for photo
    let randomIndexPhoto = Math.floor(Math.random() * arrBg.length)
    bgImage.src = arrBg[randomIndexPhoto];

    // Create RI for text
    let randomIndexText = Math.floor(Math.random() * arrTexts.length)
    mainText.innerHTML = arrTexts[randomIndexText];

    // 
    let randomIndexDecor = Math.floor(Math.random() * arrDecor.length)
    let randomDecor = arrDecor[randomIndexDecor];
    document.querySelector('.container').style.setProperty('--decor-icon', `'${randomDecor}'`);
}

